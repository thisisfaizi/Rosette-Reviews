			 * @param array $stats Store-wide rating stats.
			 */
			do_action( 'ndv-reviews/dashboard/after_kpis', $stats );
			?>

			<div class="ndvr-dash-grid">
				<section class="ndvr-card">
					<div class="ndvr-card-header">
						<h2><?php esc_html_e( 'Moderation queue', 'rosette-reviews' ); ?></h2>
						<a href="<?php echo esc_url( add_query_arg( 'status', 'moderated', $mod_url ) ); ?>"><?php esc_html_e( 'View all', 'rosette-reviews' ); ?></a>
					</div>
					<?php if ( empty( $queue ) ) : ?>
						<p class="ndvr-empty"><?php esc_html_e( 'No reviews are waiting for approval.', 'rosette-reviews' ); ?></p>
					<?php else : ?>
						<ul class="ndvr-queue">
							<?php foreach ( $queue as $c ) : ?>
								<?php $r = (int) get_comment_meta( (int) $c->comment_ID, 'rating', true ); ?>
								<li>
									<span class="ndvr-queue-stars" aria-label="<?php echo esc_attr( sprintf( /* translators: %d: star rating */ __( '%d out of 5 stars', 'rosette-reviews' ), $r ) ); ?>"><?php echo esc_html( str_repeat( '★', $r ) . str_repeat( '☆', 5 - $r ) ); ?></span>
									<div>
										<strong><?php echo esc_html( $c->comment_author ); ?></strong>
										<span><?php echo esc_html( get_the_title( (int) $c->comment_post_ID ) ); ?></span>
										<p><?php echo esc_html( wp_trim_words( $c->comment_content, 18 ) ); ?></p>
									</div>
									<a class="button button-small" href="<?php echo esc_url( add_query_arg( array( 'action' => 'edit', 'review' => (int) $c->comment_ID ), $mod_url ) ); ?>"><?php esc_html_e( 'Open', 'rosette-reviews' ); ?></a>
								</li>
							<?php endforeach; ?>
						</ul>
					<?php endif; ?>
				</section>

				<section class="ndvr-card">
					<div class="ndvr-card-header"><h2><?php esc_html_e( 'Rating distribution', 'rosette-reviews' ); ?></h2></div>
					<?php if ( ! $stats['total'] ) : ?>
						<p class="ndvr-empty"><?php esc_html_e( 'No approved reviews yet.', 'rosette-reviews' ); ?></p>
					<?php else : ?>
						<ul class="ndvr-dist">
							<?php for ( $star = 5; $star >= 1; $star-- ) : ?>
								<?php $pct = round( $stats['dist'][ $star ] / $stats['total'] * 100 ); ?>
								<li>
									<span><?php echo esc_html( $star ); ?>★</span>
									<span class="ndvr-dist-track"><span style="width:<?php echo esc_attr( (string) $pct ); ?>%"></span></span>
									<span class="ndvr-dist-n"><?php echo esc_html( number_format_i18n( $stats['dist'][ $star ] ) ); ?></span>
								</li>
							<?php endfor; ?>
						</ul>
					<?php endif; ?>
				</section>

				<section class="ndvr-card">
					<div class="ndvr-card-header">
						<h2><?php esc_html_e( 'Review reminders · 30 days', 'rosette-reviews' ); ?></h2>
						<span class="ndvr-card-status <?php echo $this->settings->get( 'reminder_enabled' ) ? 'connected' : 'disconnected'; ?>"><?php echo $this->settings->get( 'reminder_enabled' ) ? esc_html__( 'On', 'rosette-reviews' ) : esc_html__( 'Off', 'rosette-reviews' ); ?></span>
					</div>
					<div class="ndvr-mini-stats">
						<div><strong><?php echo esc_html( number_format_i18n( $reminders['sent'] + $reminders['converted'] ) ); ?></strong><span><?php esc_html_e( 'Sent', 'rosette-reviews' ); ?></span></div>
						<div><strong><?php echo esc_html( number_format_i18n( $reminders['scheduled'] ) ); ?></strong><span><?php esc_html_e( 'Scheduled', 'rosette-reviews' ); ?></span></div>
						<div class="<?php echo $reminders['failed'] ? 'is-alert' : ''; ?>"><strong><?php echo esc_html( number_format_i18n( $reminders['failed'] ) ); ?></strong><span><?php esc_html_e( 'Failed', 'rosette-reviews' ); ?></span></div>
					</div>
					<?php if ( $tracking['sent'] > 0 ) : ?>
						<h3 class="ndvr-subhead"><?php esc_html_e( 'Results · 90 days', 'rosette-reviews' ); ?></h3>
						<div class="ndvr-mini-stats">
							<div><strong><?php echo esc_html( number_format_i18n( $tracking['sent'] ) ); ?></strong><span><?php esc_html_e( 'Sent', 'rosette-reviews' ); ?></span></div>
							<div><strong><?php echo esc_html( number_format_i18n( $tracking['opened'] ) ); ?></strong><span><?php esc_html_e( 'Link opened', 'rosette-reviews' ); ?></span></div>
							<div><strong><?php echo esc_html( number_format_i18n( $tracking['reviewed'] ) ); ?></strong><span><?php esc_html_e( 'Reviewed', 'rosette-reviews' ); ?></span></div>
							<div>
								<strong><?php echo esc_html( null === $tracking['conversion'] ? '—' : number_format_i18n( $tracking['conversion'] * 100 ) . '%' ); ?></strong>
								<span><?php esc_html_e( 'Conversion', 'rosette-reviews' ); ?></span>
							</div>
						</div>
						<p class="description">
							<?php
							/* translators: 1: orders with a review, 2: orders that got a request. */
							echo esc_html( sprintf( __( '%1$s of %2$s orders that got a request left a review.', 'rosette-reviews' ), number_format_i18n( $tracking['orders_reviewed'] ), number_format_i18n( $tracking['orders_sent'] ) ) );
							?>
						</p>
					<?php endif; ?>
					<p class="ndvr-card-foot"><a href="<?php echo esc_url( admin_url( 'admin.php?page=ndv-reviews-reminders' ) ); ?>"><?php esc_html_e( 'Open reminder log', 'rosette-reviews' ); ?></a></p>
				</section>

				<section class="ndvr-card">
					<div class="ndvr-card-header"><h2><?php esc_html_e( 'Products', 'rosette-reviews' ); ?></h2></div>
					<?php if ( empty( $lists['top'] ) ) : ?>
						<p class="ndvr-empty"><?php esc_html_e( 'No product has a review yet.', 'rosette-reviews' ); ?></p>
					<?php else : ?>
						<h3 class="ndvr-subhead"><?php esc_html_e( 'Most reviewed', 'rosette-reviews' ); ?></h3>
						<ul class="ndvr-plist">
							<?php foreach ( $lists['top'] as $p ) : ?>
								<li><a href="<?php echo esc_url( get_edit_post_link( $p->get_id() ) ); ?>"><?php echo esc_html( $p->get_name() ); ?></a><span><?php echo esc_html( number_format_i18n( (float) $p->get_average_rating(), 1 ) ); ?>★ · <?php echo esc_html( number_format_i18n( $p->get_review_count() ) ); ?></span></li>
							<?php endforeach; ?>
						</ul>
						<h3 class="ndvr-subhead"><?php esc_html_e( 'Lowest rated', 'rosette-reviews' ); ?></h3>
						<ul class="ndvr-plist">
							<?php foreach ( array_slice( $lists['low'], 0, 3 ) as $p ) : ?>
								<li><a href="<?php echo esc_url( get_edit_post_link( $p->get_id() ) ); ?>"><?php echo esc_html( $p->get_name() ); ?></a><span><?php echo esc_html( number_format_i18n( (float) $p->get_average_rating(), 1 ) ); ?>★ · <?php echo esc_html( number_format_i18n( $p->get_review_count() ) ); ?></span></li>
							<?php endforeach; ?>
						</ul>
					<?php endif; ?>
				</section>
			</div>

			<?php
			/**
			 * Fires at the end of the Overview (Pro adds analytics/AI panels; free
			 * shows nothing here).
			 */
			do_action( 'ndv-reviews/dashboard/end' );
			?>
		</div>
		<?php
	}
